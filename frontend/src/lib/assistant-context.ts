export function buildAssistantContext(input: {
  page: string
  role?: string
  userName?: string
  mode: AssistantMode
}) {
  return [
    `หน้าปัจจุบัน: ${input.page}`,
    `บทบาทผู้ใช้: ${input.role ?? "NURSE"}`,
    `ชื่อผู้ใช้: ${input.userName ?? "ทีมคลินิก"}`,
    `โหมดผู้ช่วย: ${ASSISTANT_MODE_LABELS[input.mode]}`,
    `คำอธิบายโหมด: ${ASSISTANT_MODE_HINTS[input.mode]}`
  ].join("\n")
}
