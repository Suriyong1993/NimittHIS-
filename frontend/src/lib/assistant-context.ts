export function buildAssistantContext(input: {
  page: string
  role?: string
  userName?: string
}) {
  return [
    `หน้าปัจจุบัน: ${input.page}`,
    `บทบาทผู้ใช้: ${input.role ?? "NURSE"}`,
    `ชื่อผู้ใช้: ${input.userName ?? "ทีมคลินิก"}`
  ].join("\n")
}
